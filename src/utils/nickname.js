const normalize = (s) => String(s || '').toLowerCase().replace(/[\s._\-!@#$%^&*()+=~`'"<>?,/\\|[\]{}:;]/g, '');

/** 자모 분리·특수문자 끼워넣기 우회 대응: "시.발", "시 발" 등 */
const contains = (n, word) => n.includes(normalize(word));

/**
 * @returns {string} 빈 문자열이면 통과, 아니면 학생에게 보여줄 사유
 */
export const validateNickname = (raw) => {
  const s = String(raw || '').trim();
  if (!s) return '닉네임을 적어 줘.';
  if ([...s].length > NICK_MAX) return `닉네임은 ${NICK_MAX}글자까지만 쓸 수 있어.`;
  if ([...s].length < NICK_MIN) return `닉네임은 ${NICK_MIN}글자 이상으로 해 줘.`;
  if (!/^[가-힣a-zA-Z0-9 ]+$/.test(s)) return '한글·영어·숫자만 쓸 수 있어. (이모지·특수문자는 안 돼)';
  if (/^\d+$/.test(s)) return '숫자만으로는 안 돼. 글자를 넣어 줘.';
  if (/(.)\1{3,}/.test(s.replace(/\s/g, ''))) return '같은 글자를 4번 이상 반복할 수 없어.';
  const n = normalize(s);
  if (BANNED.some(w => contains(n, w))) return '이 닉네임은 쓸 수 없어. 친구들이 봐도 기분 좋은 이름으로 다시 골라 줄래?';
  return '';
};

/** 입력 중 강제: 길이·문자 제한만 즉시 적용 */
export const sanitizeNicknameInput = (raw) => [...String(raw || '').replace(/[^가-힣ㄱ-ㅎㅏ-ㅣa-zA-Z0-9 ]/g, '')].slice(0, NICK_MAX).join('');
